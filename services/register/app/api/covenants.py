"""Covenant monitoring — definitions, recurring observations, results, waivers.

The model splits configuration from observation:

* ``covenants`` (this module's CRUD) — the DEFINITION: what is tested (a financial
  metric against a threshold, or a reporting/security obligation), how often, from when,
  and how severe a breach is.
* ``monitoring_reporting`` (PRISM master table 7) — the OBSERVATIONS: one row per
  period, generated by the recurring sweep with ``record_type='Covenant'`` and
  ``details.covenant_id``. A partial UNIQUE index makes generation idempotent per
  (covenant, due date) — a sweep retry can never double-generate a period.

The lifecycle of one observation:

    Pending ──(result: passes)──▶ Compliant
            ──(result: fails)───▶ Breached ──(waive, decision-backed)──▶ Waived
            ──(due date + grace lapses unsubmitted)──▶ Overdue
    Waived  ──(waiver_valid_until lapses)──▶ Breached again (waiver_status='Expired')

* A BREACH (or an expired waiver) auto-opens an EWS case — deduped by source, so a
  re-submitted result or a sweep retry can never spawn a duplicate case.
* A WAIVER takes effect only against a durable ``kind="waiver"`` decision (senior credit
  authority, subject-bound to the observation, MANDATORY validity window) recorded on
  the single-winner decision store FIRST — the endpoint verifies the record, never a
  client field.

    POST /v1/covenants                         define a covenant
    GET  /v1/covenants?entity_id=…             a company's covenant register
    PATCH /v1/covenants/{id}                   amend threshold / schedule / active flag
    POST /v1/monitoring/{id}/result            submit a period's actual (computes breach)
    POST /v1/monitoring/{id}/waive             apply a verified, time-boxed waiver
    POST /v1/internal/covenants/run-sweep      generate + overdue + waiver-expiry (service)
"""

