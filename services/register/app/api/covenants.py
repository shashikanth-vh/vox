@router.post("/v1/covenants", tags=["Covenants"], status_code=201,
             summary="Define a covenant (schedule + test)")
async def create_covenant(payload: CovenantIn,
                          ctx: RequestContext = Depends(get_context)) -> dict[str, Any]:
    _require_manage(ctx)
    if payload.covenant_type == "Financial" and not (
            payload.metric and payload.operator and payload.threshold is not None):
        raise ValidationAppError(
            "A Financial covenant needs metric + operator + threshold "
            "(e.g. dscr >= 1.20).")
    if await load_subject(ctx.session, ctx.tenant_id, "Entity", payload.entity_id) is None:
        raise NotFoundError(f"Entity '{payload.entity_id}' not found.")
    if payload.deal_id is not None and await load_subject(
            ctx.session, ctx.tenant_id, "Deal", payload.deal_id) is None:
        raise NotFoundError(f"Deal '{payload.deal_id}' not found.")
    row = Covenant(tenant_id=ctx.tenant_id, created_by=ctx.actor,
                   **payload.model_dump())
    ctx.session.add(row)
    await ctx.session.flush()
    await ctx.session.refresh(row)
    return _serialize(row)


@router.get("/v1/covenants", tags=["Covenants"],
            summary="A company's covenant register")
async def list_covenants(entity_id: uuid.UUID,
                         ctx: RequestContext = Depends(get_context),
                         deal_id: uuid.UUID | None = None,
                         active_only: bool = True) -> dict[str, Any]:
    await _ensure_company_read(ctx, entity_id)
    conds = [Covenant.tenant_id == ctx.tenant_id, Covenant.entity_id == entity_id,
             Covenant.deleted_at.is_(None)]
    if deal_id is not None:
        conds.append(Covenant.deal_id == deal_id)
    if active_only:
        conds.append(Covenant.is_active.is_(True))
    rows = list((await ctx.session.execute(
        select(Covenant).where(*conds).order_by(Covenant.name))).scalars())
    return {"items": [_serialize(r) for r in rows]}


@router.get("/v1/covenants/observations", tags=["Covenants"],
            summary="A company's covenant OBSERVATIONS (the periods), newest due first")
async def list_observations(entity_id: uuid.UUID,
                            ctx: RequestContext = Depends(get_context),
                            lending_id: uuid.UUID | None = None,
                            status: str | None = None,
                            limit: int = 200) -> dict[str, Any]:
    """The LMS covenant tab's read: every generated period for the company's covenants —
    Pending, Compliant, Breached, Waived, Overdue — with the covenant id in details so
    the UI can pair observation to definition. Company-read gated like the register."""
    await _ensure_company_read(ctx, entity_id)
    conds = [MonitoringReporting.tenant_id == ctx.tenant_id,
             MonitoringReporting.entity_id == entity_id,
             MonitoringReporting.record_type == "Covenant",
             MonitoringReporting.deleted_at.is_(None)]
    if status is not None:
        conds.append(MonitoringReporting.status == status)
    rows = list((await ctx.session.execute(
        select(MonitoringReporting).where(*conds)
        .order_by(MonitoringReporting.due_date.desc().nulls_last())
        .limit(min(max(limit, 1), 500)))).scalars())
    if lending_id is not None:
        rows = [r for r in rows
                if (r.details or {}).get("lending_id") == str(lending_id)]
    return {"items": [_serialize_obs(r) for r in rows]}


@router.get("/v1/covenants/{covenant_id}", tags=["Covenants"], summary="One covenant")
async def get_covenant(covenant_id: uuid.UUID,
                       ctx: RequestContext = Depends(get_context)) -> dict[str, Any]:
    row = await _covenant(ctx, covenant_id)
    await _ensure_company_read(ctx, row.entity_id)
    return _serialize(row)


@router.patch("/v1/covenants/{covenant_id}", tags=["Covenants"],
              summary="Amend a covenant (threshold / grace / severity / active)")
async def update_covenant(covenant_id: uuid.UUID, payload: CovenantUpdate,
                          ctx: RequestContext = Depends(get_context)) -> dict[str, Any]:
    _require_manage(ctx)
    row = await _covenant(ctx, covenant_id)
    changes = payload.model_dump(exclude_unset=True)
    if not changes:
        raise ValidationAppError("Nothing to update.")
    before = {k: getattr(row, k) for k in changes}
    for k, v in changes.items():
        setattr(row, k, v)
    row.updated_by = ctx.actor
    row.version = (row.version or 1) + 1
    ctx.session.add(AuditLog(
        tenant_id=ctx.tenant_id, actor=ctx.actor, action="covenant.update",
        resource_type="covenants", resource_id=str(row.id),
        request_id=request_id_ctx.get(),
        changes={"before": {k: str(v) for k, v in before.items()},
                 "after": {k: str(v) for k, v in changes.items()}}))
    await ctx.session.flush()
    await ctx.session.refresh(row)
    return _serialize(row)


async def _covenant(ctx: RequestContext, covenant_id: uuid.UUID) -> Covenant:
    row = (await ctx.session.execute(
        select(Covenant).where(
            Covenant.tenant_id == ctx.tenant_id, Covenant.id == covenant_id,
            Covenant.deleted_at.is_(None)))).scalar_one_or_none()
    if row is None:
        raise NotFoundError(f"No covenant '{covenant_id}'.")
    return row


async def _observation(ctx: RequestContext,
                       monitoring_id: uuid.UUID) -> MonitoringReporting:
    row = (await ctx.session.execute(
        select(MonitoringReporting).where(
            MonitoringReporting.tenant_id == ctx.tenant_id,
            MonitoringReporting.id == monitoring_id,
            MonitoringReporting.deleted_at.is_(None)))).scalar_one_or_none()
    if row is None:
        raise NotFoundError(f"No monitoring record '{monitoring_id}'.")
    if row.record_type != "Covenant":
        raise ValidationAppError(
            f"Monitoring record '{monitoring_id}' is {row.record_type!r}, not a "
            "covenant observation.")
    return row


