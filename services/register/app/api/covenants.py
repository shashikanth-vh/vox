@router.post("/v1/monitoring/{monitoring_id}/result", tags=["Covenants"],
             summary="Submit a covenant period's result (computes breach)")
async def submit_result(monitoring_id: uuid.UUID, payload: ResultIn,
                        ctx: RequestContext = Depends(get_context)) -> dict[str, Any]:
    _require_manage(ctx)
    row = await _observation(ctx, monitoring_id)
    if row.status in ("Compliant", "Breached", "Waived"):
        raise ConflictError(
            f"Observation already has a result ({row.status}); a corrected figure is a "
            "governance event — waive or escalate, never overwrite.")
    details = dict(row.details or {})
    operator, threshold = details.get("operator"), row.target_value
    submitted = payload.submitted_on or datetime.now(UTC).date()
    row.submitted_date = submitted
    if row.due_date is not None:
        row.on_time = submitted <= row.due_date
        row.delay_days = max((submitted - row.due_date).days, 0)
    breached = False
    if operator and threshold is not None:
        if payload.actual_value is None:
            raise ValidationAppError(
                "This is a FINANCIAL covenant observation — actual_value is required.")
        row.actual_value = payload.actual_value
        breached = breach_test(str(operator), float(threshold), payload.actual_value)
    row.breached = breached
    row.status = "Breached" if breached else "Compliant"
    if payload.note:
        details["result_note"] = payload.note
        row.details = details
    row.updated_by = ctx.actor
    row.version = (row.version or 1) + 1
    ctx.session.add(AuditLog(
        tenant_id=ctx.tenant_id, actor=ctx.actor, action="covenant.result",
        resource_type="monitoring_reporting", resource_id=str(row.id),
        request_id=request_id_ctx.get(),
        changes={"actual_value": payload.actual_value, "breached": breached,
                 "covenant": row.covenant_name}))
    case_id = None
    if breached:
        # A breach IS an early-warning trigger — the case opens in the SAME transaction
        # as the result, so a recorded breach can never silently lack its case.
        case_id = await _open_ews_case(
            ctx, entity_id=row.entity_id, deal_id=row.deal_id,
            source="covenant", source_ref=str(row.id),
            severity=str(details.get("breach_severity") or "Amber"),
            title=f"Covenant breach — {row.covenant_name}",
            summary=(f"{details.get('metric')} {operator} {threshold} tested at "
                     f"{payload.actual_value} for period {row.period}"))
    await ctx.session.flush()
    await ctx.session.refresh(row)
    return {**_serialize_obs(row), "ews_case_id": case_id}


