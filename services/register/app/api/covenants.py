@router.post("/v1/internal/covenants/run-sweep", tags=["Internal"],
             summary="Covenant sweep: generate due observations, mark overdue, expire "
                     "lapsed waivers (idempotent)")
async def run_sweep(payload: SweepIn,
                    ctx: RequestContext = Depends(get_context)) -> dict[str, Any]:
    if service_ctx.get() not in _SWEEP_SERVICES:
        raise ForbiddenError(
            "The covenant sweep runs under the workflow service principal only.")
    today = datetime.now(UTC).date()
    horizon = today + timedelta(days=payload.horizon_days)

    # 1. GENERATE the schedule's observations up to the horizon. The partial unique
    #    index absorbs everything already generated — replay-safe by construction.
    covenants = list((await ctx.session.execute(
        select(Covenant).where(
            Covenant.tenant_id == ctx.tenant_id, Covenant.is_active.is_(True),
            Covenant.deleted_at.is_(None)))).scalars())
    generated = 0
    for cov in covenants:
        if cov.first_due_on is None:      # deferred — stamps at first disbursement
            continue
        for due in due_dates(cov.first_due_on, cov.frequency, horizon):
            won = (await ctx.session.execute(
                pg_insert(MonitoringReporting).values(
                    tenant_id=ctx.tenant_id, entity_id=cov.entity_id,
                    deal_id=cov.deal_id, record_type="Covenant",
                    covenant_name=cov.name, due_date=due, period=due.isoformat(),
                    status="Pending", target_value=cov.threshold,
                    details={"covenant_id": str(cov.id), "metric": cov.metric,
                             "operator": cov.operator,
                             "breach_severity": cov.breach_severity,
                             "grace_days": cov.grace_days,
                             "lending_id": str(cov.lending_id) if cov.lending_id
                             else None},
                    created_by=ctx.actor)
                # Bare ON CONFLICT DO NOTHING: the only unique constraint these values
                # can hit is the partial covenant-period index, and "already generated"
                # is exactly the no-op we want — replay-safe by construction.
                .on_conflict_do_nothing()
                .returning(MonitoringReporting.id))).scalar_one_or_none()
            if won is not None:
                generated += 1

    # 2. NEWLY OVERDUE: due + grace lapsed with nothing submitted. The status flip makes
    #    this report-once (an already-Overdue row no longer matches).
    overdue_rows = (await ctx.session.execute(text(
        "UPDATE monitoring_reporting SET status = 'Overdue', on_time = false, "
        "delay_days = (:today - due_date), updated_by = :actor "
        "WHERE tenant_id = :tid AND deleted_at IS NULL AND record_type = 'Covenant' "
        "AND submitted_date IS NULL AND status = 'Pending' "
        "AND due_date + COALESCE((details->>'grace_days')::int, 0) < :today "
        "RETURNING id, covenant_name, due_date, entity_id, deal_id, period"),
        {"today": today, "actor": ctx.actor,
         "tid": str(ctx.tenant_id)})).mappings().all()

    # 3. LAPSED WAIVERS: the excuse expires, the breach is LIVE again, and a fresh EWS
    #    case opens (deduped per observation under the waiver_expiry source).
    expired_rows = (await ctx.session.execute(text(
        "UPDATE monitoring_reporting SET waiver_status = 'Expired', "
        "status = 'Breached', updated_by = :actor "
        "WHERE tenant_id = :tid AND deleted_at IS NULL AND record_type = 'Covenant' "
        "AND waiver_status = 'Granted' AND waiver_valid_until < :today "
        "RETURNING id, covenant_name, due_date, entity_id, deal_id, period, "
        "waiver_decision_ref"),
        {"today": today, "actor": ctx.actor,
         "tid": str(ctx.tenant_id)})).mappings().all()
    for r in expired_rows:
        await _open_ews_case(
            ctx, entity_id=r["entity_id"], deal_id=r["deal_id"],
            source="waiver_expiry", source_ref=str(r["id"]), severity="Red",
            title=f"Waiver expired — {r['covenant_name']}",
            summary=(f"The waiver ({r['waiver_decision_ref']}) on period "
                     f"{r['period']} lapsed; the breach is live again."))
        ctx.session.add(AuditLog(
            tenant_id=ctx.tenant_id, actor=ctx.actor, action="covenant.waiver_expired",
            resource_type="monitoring_reporting", resource_id=str(r["id"]),
            request_id=request_id_ctx.get(),
            changes={"covenant": r["covenant_name"],
                     "decision_ref": r["waiver_decision_ref"]}))

    def _dump(r: Any) -> dict[str, Any]:
        return {"id": str(r["id"]), "covenant_name": r["covenant_name"],
                "due_date": r["due_date"].isoformat() if r["due_date"] else None,
                "entity_id": str(r["entity_id"]),
                "deal_id": str(r["deal_id"]) if r["deal_id"] else None,
                "period": r["period"]}

    return {"swept_on": today.isoformat(), "generated": generated,
            "overdue": [_dump(r) for r in overdue_rows[:payload.limit]],
            "waivers_expired": [_dump(r) for r in expired_rows[:payload.limit]]}
