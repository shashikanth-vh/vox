_FREQUENCY_MONTHS = {"Monthly": 1, "Quarterly": 3, "SemiAnnual": 6, "Annual": 12}


class CovenantIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    entity_id: uuid.UUID
    deal_id: uuid.UUID | None = None
    lending_id: uuid.UUID | None = None
    name: str = Field(min_length=1, max_length=200)
    covenant_type: str = Field(default="Financial",
                               pattern="^(Financial|Reporting|Security|Other)$")
    description: str | None = Field(default=None, max_length=4000)
    metric: str | None = Field(default=None, max_length=60)      # e.g. "dscr"
    operator: str | None = Field(default=None, pattern="^(>=|<=|>|<|=)$")
    threshold: float | None = None
    frequency: str = Field(default="Quarterly",
                           pattern="^(OneTime|Monthly|Quarterly|SemiAnnual|Annual)$")
    first_due_on: date
    grace_days: int = Field(default=0, ge=0, le=365)
    breach_severity: str = Field(default="Amber", pattern="^(Amber|Red)$")


class CovenantUpdate(BaseModel):
    model_config = ConfigDict(extra="forbid")
    description: str | None = Field(default=None, max_length=4000)
    threshold: float | None = None
    grace_days: int | None = Field(default=None, ge=0, le=365)
    breach_severity: str | None = Field(default=None, pattern="^(Amber|Red)$")
    is_active: bool | None = None


class ResultIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    # The tested value for a FINANCIAL covenant; a reporting/security obligation submits
    # without one (the submission itself is the compliance).
    actual_value: float | None = None
    submitted_on: date | None = None
    note: str | None = Field(default=None, max_length=4000)


class WaiveIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    # The durable waiver decision (kind="waiver") this waiver is backed by.
    decision_ref: str = Field(min_length=1, max_length=200)
    note: str | None = Field(default=None, max_length=4000)


class SweepIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    # How far ahead observations are generated.
    horizon_days: int = Field(default=30, ge=0, le=400)
    limit: int = Field(default=500, ge=1, le=2000)


def _require_manage(ctx: RequestContext) -> None:
    authz.enforce_operation(ctx.user, "manage_covenants")


def _serialize(c: Covenant) -> dict[str, Any]:
    return {"id": str(c.id), "entity_id": str(c.entity_id),
            "deal_id": str(c.deal_id) if c.deal_id else None,
            "lending_id": str(c.lending_id) if c.lending_id else None,
            "name": c.name, "covenant_type": c.covenant_type,
            "description": c.description, "metric": c.metric, "operator": c.operator,
            "threshold": float(c.threshold) if c.threshold is not None else None,
            "frequency": c.frequency,
            "first_due_on": c.first_due_on.isoformat() if c.first_due_on else None,
            "grace_days": c.grace_days, "breach_severity": c.breach_severity,
            "is_active": c.is_active, "version": c.version}


def _serialize_obs(m: MonitoringReporting) -> dict[str, Any]:
    return {"id": str(m.id), "entity_id": str(m.entity_id),
            "deal_id": str(m.deal_id) if m.deal_id else None,
            "record_type": m.record_type, "covenant_name": m.covenant_name,
            "due_date": m.due_date.isoformat() if m.due_date else None,
            "submitted_date": m.submitted_date.isoformat() if m.submitted_date else None,
            "on_time": m.on_time, "delay_days": m.delay_days, "period": m.period,
            "status": m.status,
            "target_value": float(m.target_value) if m.target_value is not None else None,
            "actual_value": float(m.actual_value) if m.actual_value is not None else None,
            "breached": m.breached, "waiver_status": m.waiver_status,
            "waiver_valid_until": (m.waiver_valid_until.isoformat()
                                   if m.waiver_valid_until else None),
            "waiver_decision_ref": m.waiver_decision_ref,
            "details": m.details}


def add_months(d: date, months: int) -> date:
    """Month arithmetic with day clamping (Jan 31 + 1 month → Feb 28) — schedule
    projection must never skip or crash on short months."""
    total = (d.year * 12 + (d.month - 1)) + months
    year, month = divmod(total, 12)
    month += 1
    for day in (d.day, 30, 29, 28):
        try:
            return date(year, month, day)
        except ValueError:
            continue
    raise ValueError(f"cannot add {months} months to {d}")  # pragma: no cover


def due_dates(first_due_on: date, frequency: str, horizon: date,
              cap: int = 400) -> list[date]:
    """Every due date of the schedule up to (and including) ``horizon``. OneTime yields
    at most its single date; recurring schedules are bounded by ``cap`` periods."""
    if first_due_on > horizon:
        return []
    step = _FREQUENCY_MONTHS.get(frequency)
    if step is None:                       # OneTime
        return [first_due_on]
    out: list[date] = []
    for k in range(cap):
        due = add_months(first_due_on, step * k)
        if due > horizon:
            break
        out.append(due)
    return out


def breach_test(operator: str, threshold: float, actual: float) -> bool:
    """True = BREACHED (the covenant test FAILED)."""
    ok = {">=": actual >= threshold, "<=": actual <= threshold,
          ">": actual > threshold, "<": actual < threshold,
          "=": actual == threshold}[operator]
    return not ok


async def _open_ews_case(ctx: RequestContext, *, entity_id: uuid.UUID,
                         deal_id: uuid.UUID | None, source: str, source_ref: str,
                         severity: str, title: str, summary: str | None) -> str | None:
    """Open (or attach to) the EWS case for a trigger source — idempotent at the database
    (UNIQUE (tenant, source, source_ref)), so a re-submitted result or a sweep retry can
    never spawn a duplicate case. Returns the case id (existing or new)."""
    won = (await ctx.session.execute(
        pg_insert(EwsCase).values(
            tenant_id=ctx.tenant_id, entity_id=entity_id, deal_id=deal_id,
            source=source, source_ref=source_ref, severity=severity, title=title,
            summary=summary, status="Open", opened_by=ctx.actor, created_by=ctx.actor)
        .on_conflict_do_nothing(constraint="ews_cases_source_dedupe")
        .returning(EwsCase.id))).scalar_one_or_none()
    if won is not None:
        ctx.session.add(AuditLog(
            tenant_id=ctx.tenant_id, actor=ctx.actor, action="ews.open",
            resource_type="ews_cases", resource_id=str(won),
            request_id=request_id_ctx.get(),
            changes={"source": source, "source_ref": source_ref, "severity": severity}))
        return str(won)
    existing = (await ctx.session.execute(
        select(EwsCase.id).where(
            EwsCase.tenant_id == ctx.tenant_id, EwsCase.source == source,
            EwsCase.source_ref == source_ref))).scalar_one_or_none()
    return str(existing) if existing else None


