@router.post("/v1/monitoring/{monitoring_id}/waive", tags=["Covenants"],
             summary="Apply a verified, time-boxed covenant waiver")
async def waive_breach(monitoring_id: uuid.UUID, payload: WaiveIn,
                       ctx: RequestContext = Depends(get_context)) -> dict[str, Any]:
    _require_manage(ctx)
    row = await _observation(ctx, monitoring_id)
    if not row.breached or row.status not in ("Breached",):
        raise ConflictError(
            f"Observation is {row.status!r}; only a live Breached observation can be "
            "waived.")
    # VERIFY the durable waiver decision — subject-bound, Approved, senior authority,
    # with a MANDATORY validity window. The waiver takes effect from the RECORD, never
    # from the caller's say-so.
    dec = (await ctx.session.execute(
        select(WorkflowDecision).where(
            WorkflowDecision.tenant_id == ctx.tenant_id,
            WorkflowDecision.workflow_id == payload.decision_ref))).scalar_one_or_none()
    if dec is None:
        raise ValidationAppError(
            f"No decision recorded under reference '{payload.decision_ref}'.")
    if dec.subject_type != "Monitoring" or str(dec.subject_id) != str(row.id):
        raise ValidationAppError(
            "The referenced decision is not a waiver for THIS observation.")
    if dec.decision != "Approved":
        raise ValidationAppError(
            f"The referenced decision is {dec.decision!r} — only an Approved waiver "
            "decision can excuse a breach.")
    from evam_backend_core.rbac_catalog import canonical_roles
    if not (canonical_roles(dec.roles) & _WAIVER_AUTHORITY):
        raise ForbiddenError(
            "The referenced decision was not made with senior credit authority "
            f"(one of {sorted(_WAIVER_AUTHORITY)}).")
    if not dec.valid_days:
        raise ValidationAppError(
            "A waiver must be TIME-BOXED — the decision carries no valid_days.")
    row.waiver_status = "Granted"
    row.waiver_decision_ref = payload.decision_ref
    row.waiver_valid_until = datetime.now(UTC).date() + timedelta(days=dec.valid_days)
    row.waiver_note = payload.note or dec.note
    row.status = "Waived"
    row.updated_by = ctx.actor
    row.version = (row.version or 1) + 1
    ctx.session.add(AuditLog(
        tenant_id=ctx.tenant_id, actor=ctx.actor, action="covenant.waive",
        resource_type="monitoring_reporting", resource_id=str(row.id),
        request_id=request_id_ctx.get(),
        changes={"decision_ref": payload.decision_ref, "granted_by": dec.decided_by,
                 "valid_until": row.waiver_valid_until.isoformat()}))
    await ctx.session.flush()
    await ctx.session.refresh(row)
    return _serialize_obs(row)


